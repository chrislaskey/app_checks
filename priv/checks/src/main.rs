//! Runs the checks the config enabled, in the order given.
//!
//! The state of the code is gathered once, from git, and given to every
//! check: every file in the project, and every file the branch changed
//! since it left `--base`, with the lines it changed. Each check runs with
//! its own config and returns violations, which print with the check's
//! level. Exits `1` when any violation is an error, `0` otherwise, and `2`
//! when the arguments, the config or git are wrong.
//!
//! Options, all filled in by `mix app_checks` from `.app_checks.exs`:
//!
//! - `--base REF` is the git ref the branch is compared with, `main` when
//!   not given. Git is only read. Nothing is fetched or changed.
//! - `--enable NAME` runs the check called `NAME`. Repeatable, in order.
//! - `--disable NAME` names a check the config turned off, so the summary
//!   can count the checks the config does not mention at all.
//! - `--level NAME=error|warning` is what a violation from `NAME` means.
//!   `error` when not given.
//! - `--scope NAME=all|changed` is which files `NAME` looks at. `all` when
//!   not given.
//! - `--set NAME.KEY=VALUE` gives one of the check's own config keys.
//! - `--verbose` prints every stage as it happens, not only the result.
//!
//! Paths after the options narrow both file lists to what is under them.

mod check;

mod checks {
    //! The list of checks. Generated by `build.rs` from the files in
    //! `src/checks/`, so there is nothing to edit here when adding one.
    include!(concat!(env!("OUT_DIR"), "/checks.rs"));
}

use std::collections::HashMap;
use std::ops::Range;
use std::path::{Component, Path, PathBuf};
use std::process::{Command, ExitCode};

use check::{ChangedFile, Check, Config, File, Level, Lines, Output, Scope, State};

const DEFAULT_BASE: &str = "main";

#[derive(Debug, PartialEq, Eq)]
struct Options {
    base: String,
    enabled: Vec<String>,
    disabled: Vec<String>,
    /// `(NAME, LEVEL)` as given.
    levels: Vec<(String, String)>,
    /// `(NAME, SCOPE)` as given.
    scopes: Vec<(String, String)>,
    /// `(NAME.KEY, VALUE)` as given.
    settings: Vec<(String, String)>,
    verbose: bool,
    roots: Vec<PathBuf>,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            base: DEFAULT_BASE.to_string(),
            enabled: Vec::new(),
            disabled: Vec::new(),
            levels: Vec::new(),
            scopes: Vec::new(),
            settings: Vec::new(),
            verbose: false,
            roots: Vec::new(),
        }
    }
}

fn main() -> ExitCode {
    match run() {
        Ok(0) => ExitCode::SUCCESS,
        Ok(_) => ExitCode::FAILURE,
        Err(message) => {
            eprintln!("{message}");
            ExitCode::from(2)
        }
    }
}

/// Runs everything and returns how many violations were errors, or the
/// message to print before exiting with `2`.
fn run() -> Result<usize, String> {
    let options = parse_args(std::env::args().skip(1))?;
    let all = checks::all();
    let enabled = select_checks(&all, &options)?;

    // Prepare before anything runs or prints, so a bad config stops the
    // run cleanly.
    for (check, config) in &enabled {
        check
            .prepare(config)
            .map_err(|message| format!("{}: {message}", check.name()))?;
    }

    let state = collect_state(&options.base, Path::new("."), &options.roots)?;

    let mut errors = 0;
    let mut warnings = 0;

    for (check, config) in &enabled {
        let violations = check
            .run(&state, config)
            .map_err(|message| format!("{}: {message}", check.name()))?;

        // Whatever the check printed as it went is not printed again.
        let mut rest = config.unreported(&violations);
        rest.sort_by(|a, b| a.path.cmp(&b.path).then(a.line.cmp(&b.line)));
        for violation in rest {
            config.report(violation);
        }

        match config.level() {
            Level::Error => errors += violations.len(),
            Level::Warning => warnings += violations.len(),
        }
    }

    let not_listed = all.len() - enabled.len() - options.disabled.len();
    let not_listed = match not_listed {
        0 => String::new(),
        n => format!(", {n} not listed"),
    };
    println!(
        "{} check(s), {errors} error(s), {warnings} warning(s){not_listed}",
        enabled.len()
    );

    Ok(errors)
}

fn parse_args(args: impl Iterator<Item = String>) -> Result<Options, String> {
    let mut args = args.peekable();
    let mut options = Options::default();

    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--base" => options.base = value_for(&mut args, &arg)?,
            "--enable" => options.enabled.push(value_for(&mut args, &arg)?),
            "--disable" => options.disabled.push(value_for(&mut args, &arg)?),
            "--level" => options
                .levels
                .push(pair(&value_for(&mut args, &arg)?, &arg)?),
            "--scope" => options
                .scopes
                .push(pair(&value_for(&mut args, &arg)?, &arg)?),
            "--set" => {
                let setting = value_for(&mut args, &arg)?;
                let (key, value) = setting
                    .split_once('=')
                    .ok_or_else(|| format!("--set {setting} must be NAME.KEY=VALUE"))?;
                options.settings.push((key.to_string(), value.to_string()));
            }
            "--verbose" => options.verbose = true,
            flag if flag.starts_with("--") => {
                return Err(format!(
                    "unknown option {flag}; the options are --base REF, --enable NAME, --disable NAME, \
                     --level NAME=LEVEL, --scope NAME=SCOPE, --set NAME.KEY=VALUE and --verbose"
                ));
            }
            path => options.roots.push(PathBuf::from(path)),
        }
    }

    Ok(options)
}

fn value_for(args: &mut impl Iterator<Item = String>, flag: &str) -> Result<String, String> {
    args.next()
        .ok_or_else(|| format!("{flag} needs a value after it"))
}

fn pair(value: &str, flag: &str) -> Result<(String, String), String> {
    value
        .split_once('=')
        .map(|(name, value)| (name.to_string(), value.to_string()))
        .ok_or_else(|| format!("{flag} {value} must be NAME=VALUE"))
}

/// The enabled checks with their configs, in the order enabled. Every name
/// in the options must be a check, a check may not be enabled twice or both
/// enabled and disabled, and a level, scope or key may only be given for an
/// enabled check and must be one it accepts. Each is an error, so a typo
/// cannot quietly do nothing.
fn select_checks<'a>(
    all: &[&'a dyn Check],
    options: &Options,
) -> Result<Vec<(&'a dyn Check, Config)>, String> {
    let find = |name: &str| {
        all.iter()
            .copied()
            .find(|check| check.name() == name)
            .ok_or_else(|| {
                format!(
                    "there is no check called {name}; the checks are: {}",
                    names(all)
                )
            })
    };

    for name in options.enabled.iter().chain(&options.disabled) {
        find(name)?;
    }
    for (index, name) in options.enabled.iter().enumerate() {
        if options.enabled[..index].contains(name) {
            return Err(format!("{name} is enabled twice"));
        }
        if options.disabled.contains(name) {
            return Err(format!("{name} is both enabled and disabled"));
        }
    }

    let enabled_only = |what: &str, name: &str| -> Result<(), String> {
        if options.enabled.contains(&name.to_string()) {
            Ok(())
        } else {
            Err(format!("cannot give {what} for {name}, it is not enabled"))
        }
    };

    let mut levels: HashMap<&str, Level> = HashMap::new();
    for (name, level) in &options.levels {
        enabled_only("a level", name)?;
        levels.insert(name, level.parse().map_err(|e| format!("{name}: {e}"))?);
    }

    let mut scopes: HashMap<&str, Scope> = HashMap::new();
    for (name, scope) in &options.scopes {
        enabled_only("a scope", name)?;
        scopes.insert(name, scope.parse().map_err(|e| format!("{name}: {e}"))?);
    }

    let mut entries: HashMap<&str, Vec<(String, String)>> = HashMap::new();
    for (key, value) in &options.settings {
        let (name, rest) = key
            .split_once('.')
            .ok_or_else(|| format!("--set {key}={value} must be NAME.KEY=VALUE"))?;
        let check = find(name)?;
        enabled_only(&format!("the key {rest}"), name)?;
        let accepted = check.config_keys();
        if !Config::accepts(accepted, rest) {
            return Err(if accepted.is_empty() {
                format!("cannot set {key}, {name} takes no config")
            } else {
                format!(
                    "cannot set {key}, {name} does not accept {rest}; it accepts: {}",
                    accepted.join(", ")
                )
            });
        }
        entries
            .entry(name)
            .or_default()
            .push((rest.to_string(), value.clone()));
    }

    let output = Output {
        verbose: options.verbose,
        quiet: false,
    };

    options
        .enabled
        .iter()
        .map(|name| {
            let check = find(name)?;
            let config = Config::new(
                check.name(),
                levels.get(name.as_str()).copied().unwrap_or(Level::Error),
                scopes.get(name.as_str()).copied().unwrap_or(Scope::All),
                entries.remove(name.as_str()).unwrap_or_default(),
                output,
            );
            Ok((check, config))
        })
        .collect()
}

fn names(checks: &[&dyn Check]) -> String {
    checks
        .iter()
        .map(|check| check.name())
        .collect::<Vec<_>>()
        .join(", ")
}

/// The state of the code in the repository at `dir`: every file git
/// tracks or could track, and every file the branch changed since it left
/// `base`, with the lines it changed. Commits, staged and unstaged edits
/// and untracked files all count. Paths are relative to `dir`, which is
/// where the files are read from. Only paths under one of `roots` are kept
/// when any are given. Git is only read. Nothing is fetched or changed.
fn collect_state(base: &str, dir: &Path, roots: &[PathBuf]) -> Result<State, String> {
    let merge_base = merge_base(base, dir)?;

    let tracked = git(dir, &["ls-files", "-z", "--cached"])?;
    let untracked = git(dir, &["ls-files", "-z", "--others", "--exclude-standard"])?;
    let diffed = git(
        dir,
        &[
            "diff",
            "--name-only",
            "--no-renames",
            "--relative",
            "-z",
            &merge_base,
        ],
    )?;
    let lines = ChangedLines::parse(&String::from_utf8_lossy(&git(
        dir,
        &[
            "-c",
            "core.quotePath=false",
            "diff",
            "-U0",
            "--no-renames",
            "--no-ext-diff",
            "--no-color",
            "--relative",
            "--src-prefix=a/",
            "--dst-prefix=b/",
            &merge_base,
        ],
    )?));

    let roots: Vec<PathBuf> = roots.iter().map(|root| without_cur_dir(root)).collect();
    let under_roots =
        |path: &Path| roots.is_empty() || roots.iter().any(|root| path.starts_with(root));

    let all: Vec<File> = paths(&[tracked.as_slice(), untracked.as_slice()])
        .into_iter()
        .filter(|path| under_roots(path) && dir.join(path).is_file())
        .map(File::new)
        .collect();

    let changed: Vec<ChangedFile> = paths(&[diffed.as_slice(), untracked.as_slice()])
        .into_iter()
        .filter(|path| under_roots(path))
        .map(|path| {
            let lines = match lines.0.get(&path) {
                Some(ranges) => Lines::Only(ranges.clone()),
                None => Lines::All,
            };
            ChangedFile { path, lines }
        })
        .collect();

    Ok(State::new(base, all, changed))
}

/// The paths in NUL separated git output, sorted, without repeats.
fn paths(outputs: &[&[u8]]) -> Vec<PathBuf> {
    let mut paths: Vec<PathBuf> = outputs
        .iter()
        .flat_map(|output| {
            output
                .split(|byte| *byte == 0)
                .filter(|path| !path.is_empty())
                .map(|path| PathBuf::from(String::from_utf8_lossy(path).into_owned()))
                .collect::<Vec<_>>()
        })
        .collect();
    paths.sort();
    paths.dedup();
    paths
}

/// The commit where the branch left `base`, which is what it is compared
/// with, so commits that landed on the base afterwards do not count.
fn merge_base(base: &str, dir: &Path) -> Result<String, String> {
    let output = git(dir, &["merge-base", base, "HEAD"]).map_err(|error| {
        format!(
            "could not find where the branch left {base}: {error}\n\
             Fetch the base branch, pass --base REF, or set base_ref in .app_checks.exs"
        )
    })?;
    Ok(String::from_utf8_lossy(&output).trim().to_string())
}

/// The lines the branch added or changed, by file, from `git diff -U0`. A
/// file that is listed with no lines only had lines removed.
struct ChangedLines(HashMap<PathBuf, Vec<Range<usize>>>);

impl ChangedLines {
    /// Reads a `diff --git a/PATH b/PATH` header per file, then
    /// `@@ -OLD +START,COUNT @@` per hunk, where `START,COUNT` are the
    /// lines on the new side. A count of 0 is a pure removal.
    fn parse(diff: &str) -> Self {
        let mut lines: HashMap<PathBuf, Vec<Range<usize>>> = HashMap::new();
        let mut current: Option<PathBuf> = None;

        for line in diff.lines() {
            if let Some(path) = diff_header_path(line) {
                lines.entry(path.clone()).or_default();
                current = Some(path);
            } else if let (Some(path), Some(range)) = (&current, hunk_added_lines(line)) {
                if !range.is_empty() {
                    lines.entry(path.clone()).or_default().push(range);
                }
            }
        }

        Self(lines)
    }
}

/// The path in a `diff --git a/PATH b/PATH` line. Renames are off, so both
/// sides are the same path, which is how a path with spaces is read back.
fn diff_header_path(line: &str) -> Option<PathBuf> {
    let rest = line.strip_prefix("diff --git a/")?;
    let len = rest.len().checked_sub(3)? / 2;
    let path = rest.get(..len)?;
    (rest.get(len..)? == format!(" b/{path}")).then(|| PathBuf::from(path))
}

/// The new-side lines of a `@@ -OLD +START,COUNT @@` hunk header. A missing
/// count is 1.
fn hunk_added_lines(line: &str) -> Option<Range<usize>> {
    let added = line
        .strip_prefix("@@ ")?
        .split(' ')
        .find_map(|part| part.strip_prefix('+'))?;
    let (start, count) = match added.split_once(',') {
        Some((start, count)) => (start.parse().ok()?, count.parse().ok()?),
        None => (added.parse().ok()?, 1),
    };
    Some(start..start + count)
}

fn git(dir: &Path, args: &[&str]) -> Result<Vec<u8>, String> {
    let output = Command::new("git")
        .args(args)
        .current_dir(dir)
        .output()
        .map_err(|error| format!("could not run git: {error}"))?;

    if output.status.success() {
        Ok(output.stdout)
    } else {
        Err(format!(
            "git {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr).trim()
        ))
    }
}

/// `./lib` as `lib`, so it compares equal to the paths git prints.
fn without_cur_dir(path: &Path) -> PathBuf {
    path.components()
        .filter(|component| *component != Component::CurDir)
        .collect()
}

