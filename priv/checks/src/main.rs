    /// A throwaway repository with one commit on a branch called `base`, and
    /// on top of it: a commit changing `b.txt`, an unstaged edit to `a.txt`,
    /// a renamed `r.txt`, an untracked `c.txt` and an ignored `ignored.txt`.
    fn temp_repo(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("checks-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("lib")).unwrap();

        let sh = |args: &[&str]| {
            let status = Command::new("git")
                .args([
                    "-c",
                    "user.name=t",
                    "-c",
                    "user.email=t@t",
                    "-c",
                    "commit.gpgsign=false",
                ])
                .args(args)
                .current_dir(&dir)
                .output()
                .unwrap();
            assert!(
                status.status.success(),
                "git {args:?}: {}",
                String::from_utf8_lossy(&status.stderr)
            );
        };
        let write = |name: &str, contents: &str| std::fs::write(dir.join(name), contents).unwrap();

        sh(&["init", "-q"]);
        write(".gitignore", "ignored.txt\n");
        write("a.txt", "a\n");
        write("b.txt", "b\n");
        write("r.txt", "r\n");
        write("lib/keep.txt", "k\n");
        sh(&["add", "."]);
        sh(&["commit", "-q", "-m", "first"]);
        sh(&["branch", "base"]);

        write("b.txt", "b2\n");
        sh(&["mv", "r.txt", "renamed.txt"]);
        sh(&["commit", "-q", "-a", "-m", "second"]);
        write("a.txt", "a2\n");
        write("c.txt", "c\n");
        write("ignored.txt", "i\n");

        dir
    }

