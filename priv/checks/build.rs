//! Generates the list of checks, so adding a check is adding a file.
//!
//! Every `.rs` file in `src/checks/` is a built-in check. Every `.rs` file
//! in the directory named by the `APP_CHECKS_CUSTOM` environment variable
//! is a check of the project's own, compiled in with the built-in ones.
//! `mix app_checks` sets the variable from the `custom_checks` key of
//! `.app_checks.exs` when that directory exists.
//!
//! A file must export `pub const CHECK: &dyn Check`, and its `name()` must
//! equal the file name without `.rs`, which a generated test enforces. The
//! output is included by `main.rs` as the `checks` module.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const CUSTOM_DIR: &str = "APP_CHECKS_CUSTOM";

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let builtin_dir = Path::new(&manifest_dir).join("src").join("checks");
    let out_path = Path::new(&env::var("OUT_DIR").unwrap()).join("checks.rs");

    // Rebuild when a check is added, removed or edited in either place, or
    // when the custom directory changes.
    println!("cargo:rerun-if-changed={}", builtin_dir.display());
    println!("cargo:rerun-if-env-changed={CUSTOM_DIR}");

    let mut checks = list_checks(&builtin_dir);

    if let Some(custom_dir) = env::var_os(CUSTOM_DIR).filter(|dir| !dir.is_empty()) {
        let custom_dir = PathBuf::from(custom_dir);
        println!("cargo:rerun-if-changed={}", custom_dir.display());

        for (name, file) in list_checks(&custom_dir) {
            if checks.iter().any(|(builtin, _)| *builtin == name) {
                panic!(
                    "{}: a built-in check is already called {name}, rename the file",
                    file.display()
                );
            }
            checks.push((name, file));
        }
    }

    checks.sort();

    let mut out = String::from("// Generated by build.rs from the check files. Do not edit.\n\n");

    for (name, file) in &checks {
        out += &format!(
            "#[path = {:?}]\npub mod {name};\n",
            file.display().to_string()
        );
    }

    out += "\n/// Every check, in file name order.\n";
    out += "pub fn all() -> Vec<&'static dyn crate::check::Check> {\n    vec![\n";
    for (name, _) in &checks {
        out += &format!("        {name}::CHECK,\n");
    }
    out += "    ]\n}\n";

    out += "\n#[cfg(test)]\nmod generated_tests {\n";
    out += "    /// The config and the output refer to checks by file name.\n";
    out += "    #[test]\n    fn check_names_match_file_names() {\n";
    for (name, _) in &checks {
        out += &format!("        assert_eq!(super::{name}::CHECK.name(), {name:?});\n");
    }
    out += "    }\n}\n";

    fs::write(&out_path, out).unwrap();
}

/// Every `.rs` file directly in `dir` as `(name, path)`. A name that is not
/// a valid module name stops the build with a message, since the generated
/// code would fail with a worse one.
fn list_checks(dir: &Path) -> Vec<(String, PathBuf)> {
    let entries = fs::read_dir(dir)
        .unwrap_or_else(|error| panic!("{}: could not list the checks: {error}", dir.display()));

    entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.is_file() && path.extension().is_some_and(|ext| ext == "rs"))
        .map(|path| {
            let name = path.file_stem().unwrap().to_str().unwrap().to_string();
            if !valid_name(&name) {
                panic!(
                    "{}: a check file name must be lower case letters, digits and underscores, like no_io_inspect.rs",
                    path.display()
                );
            }
            (name, path)
        })
        .collect()
}

fn valid_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next().is_some_and(|c| c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}
